#!/usr/bin/env python3
"""Regenerates the pinned reference's agent tool definitions and the checklist in docs/agent-tools.md.

src/mcp_oauth/tools.json holds every tool the reference's /mcp server advertises, as `tools/list`
returns it (see scripts/reference_agent_tools.mjs), and the callers each is listed to. Rust lists
the ones named in `SERVED` in src/mcp_oauth/tools.rs. The checklist in docs/agent-tools.md, between
its `tools:start` and `tools:end` markers, gives each tool's toolkit, who it is listed to, the
reference's caller check (its `McpToolAccess` declaration) and whether Rust serves it.

Usage: scripts/update_agent_tools.py <reference checkout> [--check]
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOLS = ROOT / "src/mcp_oauth/tools.json"
SOURCE = ROOT / "src/mcp_oauth/tools.rs"
DOC = ROOT / "docs/agent-tools.md"
# The reference's theme constants the t3_theme_* tools use (scripts/reference_theme_constants.mjs).
THEMES = ROOT / "src/mcp_oauth/themes.json"
# The reference's agent instructions its provider adapters send (scripts/reference_agent_instructions.mjs).
INSTRUCTIONS = ROOT / "src/mcp_oauth/instructions.json"
# The reference server browser's recording encoder, which Rust's preview recordings run as it is.
RECORDING_ENCODER = ROOT / "src/local_services/browser/recording_encoder.js"
HTML_RENDER = ROOT / "src/html_render/constants.json"
# The reference's agent-device launcher (AgentDeviceShim.ts) and the value flags it skips past.
LAUNCHER = ROOT / "src/local_services/agent_device_launcher.mjs"
VALUE_FLAGS = ROOT / "src/local_services/agent_device_value_flags.txt"
# The reference's SSH device host scripts (scripts/reference_device_scripts.mjs).
DEVICE_SSH = ROOT / "src/local_services/device_ssh.json"
# The reference's Expo GraphQL operations (scripts/reference_expo_documents.mjs).
EXPO_DOCUMENTS = ROOT / "src/local_services/expo_documents.json"
START, END = "<!-- tools:start -->", "<!-- tools:end -->"

LISTED_TO = {
    "everyone": "every caller",
    "hiddenFromOutsideClients": "threads only",
    "hiddenFromSubagents": "not subagents",
    "hiddenWhileLinksOff": "links beta on",
    "hiddenWithoutBackgroundWait": "threads that can wait",
    "hiddenFromThreads": "outside clients only",
    "hiddenWithoutForge": "a forge connected",
    "hiddenWhileFeedbackOff": "feedback on",
}


def caller_checks(checkout: pathlib.Path, names: set[str]) -> dict[str, tuple[str, str]]:
    """Each tool's toolkit and its `McpToolAccess` declaration in the reference's handlers,
    outermost first, as `either(reads, writesThreads)`; a toolkit's local `writesThread` is
    `writesThreads`."""
    checks = {}
    key = re.compile(r"^\s+([a-z_0-9]+):\s*", re.M)
    access = re.compile(r"McpToolAccess\.([A-Za-z]+)\(|\bwritesThread\(")
    for path in sorted((checkout / "apps/server/src/mcp/toolkits").glob("*/handlers.ts")):
        text = path.read_text()
        starts = [m for m in key.finditer(text) if m.group(1) in names]
        for index, match in enumerate(starts):
            end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
            kinds = [m.group(1) or "writesThreads" for m in access.finditer(text, match.end(), end)]
            if not kinds or match.group(1) in checks:
                continue
            outer, inner = kinds[0], kinds[1:]
            if outer in ("either", "afterForwarding") and inner:
                count = 2 if outer == "either" else 1
                check = f"{outer}({', '.join(inner[:count])})"
            else:
                check = outer
            checks[match.group(1)] = (path.parent.name, check)
    return checks


def served() -> list[str]:
    block = re.search(r"const SERVED: &\[&str\] = &\[(.*?)\];", SOURCE.read_text(), re.S)
    if block is None:
        raise SystemExit("SERVED not found in src/mcp_oauth/tools.rs")
    return re.findall(r'"([a-z_0-9]+)"', block.group(1))


def checklist(listing: dict, checks: dict, rust: list[str]) -> str:
    rows = sorted(listing["tools"], key=lambda t: (checks.get(t["name"], ("~", ""))[0], t["name"]))
    done = sum(t["name"] in rust for t in rows)
    lines = [
        START,
        f"<!-- Generated by scripts/update_agent_tools.py: {done} of {len(rows)} served. -->",
        "",
        "| | Tool | Toolkit | Listed to | Caller check |",
        "|---|---|---|---|---|",
    ]
    for tool in rows:
        name = tool["name"]
        mark = "[x]" if name in rust else "[ ]"
        toolkit, check = checks.get(name, ("?", "?"))
        listed = listing["listedTo"][name]
        lines.append(f"| {mark} | `{name}` | {toolkit} | {LISTED_TO.get(listed, listed)} | `{check}` |")
    lines.append(END)
    return "\n".join(lines)


def recording_encoder(checkout: pathlib.Path) -> str:
    """`recordingEncoderScript`'s template, its two substitutions left for Rust to fill."""
    source = (checkout / "apps/server/src/preview/ServerBrowserPage.ts").read_text()
    head = "export const recordingEncoderScript = (frameRate: BrowserRecordingFrameRate) => `"
    start = source.index(head) + len(head)
    end = source.index("})()`;", start) + len("})()")
    body = source[start:end]
    holes = set(re.findall(r"\$\{[^}]*\}", body))
    if "\\" in body or "`" in body or holes != {"${frameRate}", "${PROVIDER_SEND_TURN_MAX_FILE_BYTES}"}:
        raise SystemExit("recordingEncoderScript is no longer a plain template; update update_agent_tools.py")
    return body + "\n"


def agent_device_launcher(checkout: pathlib.Path) -> tuple[str, str]:
    """`launcherSource`'s template, with its five substitutions as `{{NAME}}` placeholders, and
    `VALUE_FLAGS`, one per line. Neither is exported, so both are read from the source."""
    source = (checkout / "apps/server/src/device/AgentDeviceShim.ts").read_text()
    head = "`import { spawn }"
    start = source.index(head) + 1
    end = source.index("`;\n\n/** Writes a launcher", start)
    body = source[start:end]
    holes = {
        "${JSON.stringify(entryPath)}": "{{ENTRY}}",
        "${JSON.stringify(boundArgs)}": "{{BOUND}}",
        "${JSON.stringify(VALUE_FLAGS)}": "{{VALUED}}",
        "${JSON.stringify(STALE_RUNTIME)}": "{{STALE}}",
        "${JSON.stringify(node)}": "{{NODE}}",
    }
    for hole, placeholder in holes.items():
        if hole not in body:
            raise SystemExit("launcherSource changed its substitutions; update update_agent_tools.py")
        body = body.replace(hole, placeholder)
    if "${" in body:
        raise SystemExit("launcherSource has a new substitution; update update_agent_tools.py")
    # The template literal's escapes, as the string it evaluates to.
    body = re.sub(r"\\(.)", lambda match: match.group(1), body, flags=re.S)
    flags = re.search(r"const VALUE_FLAGS: ReadonlyArray<string> = \[(.*?)\];", source, re.S).group(1)
    return body, "\n".join(re.findall(r'"([^"]+)"', flags))


def main() -> int:
    checkout = pathlib.Path(sys.argv[1]).resolve()
    check = "--check" in sys.argv[2:]
    dump = subprocess.run(["node", str(ROOT / "scripts/reference_agent_tools.mjs"), str(checkout)],
                          check=True, capture_output=True, text=True).stdout
    listing = json.loads(dump)
    # tools/list sends an output schema only as effect's isToolOutputSchema allows: an object root
    # whose properties are schemas and whose required names are strings. A success that is a
    # union (`anyOf`) or anything but null (`not`) goes without one.
    for tool in listing["tools"]:
        output = tool.get("outputSchema")
        if output is not None and not (
                output.get("type") == "object"
                and all(isinstance(p, dict) for p in output.get("properties", {}).values())
                and all(isinstance(r, str) for r in output.get("required", []))):
            del tool["outputSchema"]
    names = {tool["name"] for tool in listing["tools"]}
    rust = served()
    unknown = sorted(set(rust) - names)
    if unknown:
        print(f"SERVED names tools the reference does not advertise: {unknown}")
        return 1
    tools_text = json.dumps(listing, indent=1, ensure_ascii=False) + "\n"
    doc = DOC.read_text()
    if START not in doc or END not in doc:
        print(f"{DOC.relative_to(ROOT)} has no {START} ... {END} block")
        return 1
    table = checklist(listing, caller_checks(checkout, names), rust)
    doc_text = doc[:doc.index(START)] + table + doc[doc.index(END) + len(END):]
    themes_text = subprocess.run(
        ["node", str(ROOT / "scripts/reference_theme_constants.mjs"), str(checkout)],
        check=True, capture_output=True, text=True).stdout
    instructions_text = subprocess.run(
        ["node", str(ROOT / "scripts/reference_agent_instructions.mjs"), str(checkout)],
        check=True, capture_output=True, text=True).stdout
    html_render_text = subprocess.run(
        ["node", str(ROOT / "scripts/reference_html_render.mjs"), str(checkout)],
        check=True, capture_output=True, text=True).stdout
    device_ssh_text = subprocess.run(
        ["node", str(ROOT / "scripts/reference_device_scripts.mjs"), str(checkout)],
        check=True, capture_output=True, text=True).stdout
    expo_text = subprocess.run(
        ["node", str(ROOT / "scripts/reference_expo_documents.mjs"), str(checkout)],
        check=True, capture_output=True, text=True).stdout
    launcher, value_flags = agent_device_launcher(checkout)
    outputs = ((RECORDING_ENCODER, recording_encoder(checkout)), (TOOLS, tools_text), (DOC, doc_text), (THEMES, themes_text),
               (INSTRUCTIONS, instructions_text), (HTML_RENDER, html_render_text), (LAUNCHER, launcher),
               (VALUE_FLAGS, value_flags), (DEVICE_SSH, device_ssh_text), (EXPO_DOCUMENTS, expo_text))
    stale = [path for path, text in outputs if not path.exists() or path.read_text() != text]
    if check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date; run {sys.argv[0]} {sys.argv[1]}")
        return 1 if stale else 0
    for path, text in outputs:
        path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
