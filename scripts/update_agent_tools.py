#!/usr/bin/env python3
"""Regenerates the pinned reference's agent tool definitions and the checklist in docs/agent-tools.md.

src/mcp_oauth/tools.json holds every tool the reference's /mcp server advertises, as `tools/list`
returns it (see scripts/reference_agent_tools.mjs), and the callers each is listed to. Rust lists
the ones named in `SERVED` in src/mcp_oauth/tools.rs. The checklist in docs/agent-tools.md, between
its `tools:start` and `tools:end` markers, gives each tool's toolkit, who it is listed to, the
reference's caller check (its `McpToolAccess` declaration) and whether Rust serves it.

Usage: scripts/update_agent_tools.py <reference checkout> [--check]
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOLS = ROOT / "src/mcp_oauth/tools.json"
SOURCE = ROOT / "src/mcp_oauth/tools.rs"
DOC = ROOT / "docs/agent-tools.md"
START, END = "<!-- tools:start -->", "<!-- tools:end -->"

LISTED_TO = {
    "everyone": "every caller",
    "hiddenFromOutsideClients": "threads only",
    "hiddenFromSubagents": "not subagents",
    "hiddenWhileLinksOff": "links beta on",
}


def caller_checks(checkout: pathlib.Path, names: set[str]) -> dict[str, tuple[str, str]]:
    """Each tool's toolkit and its `McpToolAccess` declaration in the reference's handlers,
    outermost first, as `either(reads, writesThreads)`; a toolkit's local `writesThread` is
    `writesThreads`."""
    checks = {}
    key = re.compile(r"^\s+([a-z_0-9]+):\s*", re.M)
    access = re.compile(r"McpToolAccess\.([A-Za-z]+)\(|\bwritesThread\(")
    for path in sorted((checkout / "apps/server/src/mcp/toolkits").glob("*/handlers.ts")):
        text = path.read_text()
        starts = [m for m in key.finditer(text) if m.group(1) in names]
        for index, match in enumerate(starts):
            end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
            kinds = [m.group(1) or "writesThreads" for m in access.finditer(text, match.end(), end)]
            if not kinds or match.group(1) in checks:
                continue
            outer, inner = kinds[0], kinds[1:]
            if outer in ("either", "afterForwarding") and inner:
                count = 2 if outer == "either" else 1
                check = f"{outer}({', '.join(inner[:count])})"
            else:
                check = outer
            checks[match.group(1)] = (path.parent.name, check)
    return checks


def served() -> list[str]:
    block = re.search(r"const SERVED: &\[&str\] = &\[(.*?)\];", SOURCE.read_text(), re.S)
    if block is None:
        raise SystemExit("SERVED not found in src/mcp_oauth/tools.rs")
    return re.findall(r'"([a-z_0-9]+)"', block.group(1))


def checklist(listing: dict, checks: dict, rust: list[str]) -> str:
    rows = sorted(listing["tools"], key=lambda t: (checks.get(t["name"], ("~", ""))[0], t["name"]))
    done = sum(t["name"] in rust for t in rows)
    lines = [
        START,
        f"<!-- Generated by scripts/update_agent_tools.py: {done} of {len(rows)} served. -->",
        "",
        "| | Tool | Toolkit | Listed to | Caller check |",
        "|---|---|---|---|---|",
    ]
    for tool in rows:
        name = tool["name"]
        mark = "[x]" if name in rust else "[ ]"
        toolkit, check = checks.get(name, ("?", "?"))
        listed = listing["listedTo"][name]
        lines.append(f"| {mark} | `{name}` | {toolkit} | {LISTED_TO.get(listed, listed)} | `{check}` |")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    checkout = pathlib.Path(sys.argv[1]).resolve()
    check = "--check" in sys.argv[2:]
    dump = subprocess.run(["node", str(ROOT / "scripts/reference_agent_tools.mjs"), str(checkout)],
                          check=True, capture_output=True, text=True).stdout
    listing = json.loads(dump)
    # tools/list sends an output schema only as effect's isToolOutputSchema allows: an object root
    # whose properties are schemas and whose required names are strings. A success that is a
    # union (`anyOf`) or anything but null (`not`) goes without one.
    for tool in listing["tools"]:
        output = tool.get("outputSchema")
        if output is not None and not (
                output.get("type") == "object"
                and all(isinstance(p, dict) for p in output.get("properties", {}).values())
                and all(isinstance(r, str) for r in output.get("required", []))):
            del tool["outputSchema"]
    names = {tool["name"] for tool in listing["tools"]}
    rust = served()
    unknown = sorted(set(rust) - names)
    if unknown:
        print(f"SERVED names tools the reference does not advertise: {unknown}")
        return 1
    tools_text = json.dumps(listing, indent=1, ensure_ascii=False) + "\n"
    doc = DOC.read_text()
    if START not in doc or END not in doc:
        print(f"{DOC.relative_to(ROOT)} has no {START} ... {END} block")
        return 1
    table = checklist(listing, caller_checks(checkout, names), rust)
    doc_text = doc[:doc.index(START)] + table + doc[doc.index(END) + len(END):]
    stale = [path for path, text in ((TOOLS, tools_text), (DOC, doc_text)) if path.read_text() != text]
    if check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date; run {sys.argv[0]} {sys.argv[1]}")
        return 1 if stale else 0
    TOOLS.write_text(tools_text)
    DOC.write_text(doc_text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
