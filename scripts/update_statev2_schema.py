#!/usr/bin/env python3
"""Regenerates src/statev2/reference_schema.sql from the pinned reference.

The reference's own migrations create a fresh statev2.sqlite (see
scripts/reference_statev2_schema.mjs); this writes its schema objects, in
creation order and with their stored text, plus its migration ledger, so a
database the Rust server creates is the one the reference would have created.

Usage: scripts/update_statev2_schema.py <reference checkout> [--check]
"""
import json
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "src/statev2/reference_schema.sql"


def render(dump: dict) -> str:
    lines = [
        "-- Generated by scripts/update_statev2_schema.py from the pinned reference.",
        "-- Do not edit: regenerate it when the pinned reference changes.",
        f"-- migration head: {dump['migrations'][-1]['migration_id']}",
        "",
    ]
    for item in dump["objects"]:
        name, sql = item["name"], item["sql"]
        # SQLite creates these itself: autoindexes, the AUTOINCREMENT ledger and
        # the FTS5 table's shadow tables.
        if sql is None or name.startswith("sqlite_"):
            continue
        if item["type"] == "table" and name.startswith("orchestration_v2_message_search_"):
            continue
        lines.append(sql + ";")
        lines.append("")
    for row in dump["migrations"]:
        lines.append(
            "INSERT INTO effect_sql_migrations (migration_id, name) VALUES "
            f"({int(row['migration_id'])}, '{row['name']}');"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    checkout = sys.argv[1]
    check = "--check" in sys.argv[2:]
    with tempfile.TemporaryDirectory() as directory:
        output = pathlib.Path(directory) / "schema.json"
        subprocess.run(
            ["node", str(ROOT / "scripts/reference_statev2_schema.mjs"), checkout, directory, str(output)],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        text = render(json.loads(output.read_text()))
    if check:
        if TARGET.read_bytes() != text.encode():
            print(f"{TARGET.relative_to(ROOT)} is out of date; run {sys.argv[0]} {checkout}")
            return 1
        return 0
    # Bytes, not text: trigger bodies hold a literal carriage return.
    TARGET.write_bytes(text.encode())
    return 0


if __name__ == "__main__":
    sys.exit(main())
