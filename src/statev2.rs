//! The reference server's orchestration database, `userdata/statev2.sqlite`.
//!
//! Both servers keep threads, runs, items and their projections here, so a
//! home switched between them sees the same state (docs/shared-store.md).
//! This module opens the database the way the reference's
//! `persistence/Sqlite.ts` does, and guards it:
//!
//! - It never migrates. A database whose migration ledger is not exactly the
//!   pinned reference's (`reference_schema.sql`) is refused with a message
//!   that says which server can open it, and is left untouched.
//! - A missing database is created with exactly the reference's schema at
//!   the pinned migration head, built beside it and published only when
//!   complete, as the reference publishes its V1 import.
//! - A home that still has only the reference's V1 `state.sqlite` is refused:
//!   the reference imports that file only when `statev2.sqlite` is absent, so
//!   creating one here would hide its threads from the reference.
pub mod outbox;
pub mod read;
pub(crate) mod scheduled_tasks;
pub mod write;

use rusqlite::{Connection, OpenFlags};
use std::path::{Path, PathBuf};
use std::sync::Arc;

/// The reference's schema at the pinned migration head, generated by
/// `scripts/update_statev2_schema.py`.
const REFERENCE_SCHEMA: &str = include_str!("statev2/reference_schema.sql");

/// The file name, in the server's state directory.
pub const FILE_NAME: &str = "statev2.sqlite";
/// The reference's V1 database, which it copies into a missing V2 one.
const V1_FILE_NAME: &str = "state.sqlite";
/// `WAL_SIZE_LIMIT_BYTES` in the reference's `Sqlite.ts`.
const WAL_SIZE_LIMIT_BYTES: i64 = 128 * 1024 * 1024;
/// The projection the reference seeds at schema creation
/// (`orchestration_v2_projection_metadata`).
const THREAD_PROJECTIONS: &str = "thread-projections";

/// Why the database cannot be used. Each says what to do; none changes it.
#[derive(Debug)]
pub enum OpenError {
    /// The ledger is below the pinned head: an older reference wrote it.
    Older {
        path: PathBuf,
        recorded: i64,
        supported: i64,
    },
    /// The ledger records migrations this build does not know.
    Newer {
        path: PathBuf,
        recorded: i64,
        supported: i64,
    },
    /// The ledger's ids match but a name differs, or one is missing.
    Divergent { path: PathBuf, detail: String },
    /// Only the reference's V1 database exists.
    UnimportedV1 { path: PathBuf },
    /// SQLite could not open or read it.
    Sqlite { path: PathBuf, source: String },
}

impl std::fmt::Display for OpenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            OpenError::Older { path, recorded, supported } => write!(
                f,
                "The T3 Code database at {} is at migration {recorded}, older than the {supported} this server supports. \
                 This server never migrates the database: start the T3 Code server version that matches migration {supported} once to upgrade it, then start this server again. The database was not changed.",
                path.display()
            ),
            OpenError::Newer { path, recorded, supported } => write!(
                f,
                "The T3 Code database at {} is at migration {recorded}, newer than the {supported} this server supports. \
                 It was written by a newer T3 Code server; use that server, or a build of this one that supports migration {recorded}. The database was not changed.",
                path.display()
            ),
            OpenError::Divergent { path, detail } => write!(
                f,
                "The T3 Code database at {} has a migration history this server does not recognise ({detail}). \
                 It was probably written by a different build; start the build that wrote it. The database was not changed.",
                path.display()
            ),
            OpenError::UnimportedV1 { path } => write!(
                f,
                "{} holds T3 Code's older database but no {FILE_NAME}. Start the T3 Code server once so it imports that database, then start this server again. Nothing was changed.",
                path.display()
            ),
            OpenError::Sqlite { path, source } => {
                write!(f, "Could not open the T3 Code database at {}: {source}", path.display())
            }
        }
    }
}

impl std::error::Error for OpenError {}

/// The migrations the pinned reference records, in order.
pub fn supported_migrations() -> Vec<(i64, String)> {
    REFERENCE_SCHEMA
        .lines()
        .filter_map(|line| {
            let rest = line
                .strip_prefix("INSERT INTO effect_sql_migrations (migration_id, name) VALUES (")?;
            let (id, name) = rest.split_once(", '")?;
            Some((id.parse().ok()?, name.strip_suffix("');")?.to_string()))
        })
        .collect()
}

/// The pinned migration head (`databaseMigration`).
pub fn supported_head() -> i64 {
    supported_migrations()
        .last()
        .map(|(id, _)| *id)
        .unwrap_or(0)
}

/// Checks a recorded ledger against the pinned one.
fn check_ledger(path: &Path, recorded: &[(i64, String)]) -> Result<(), OpenError> {
    let supported = supported_migrations();
    let head = supported_head();
    let recorded_head = recorded.iter().map(|(id, _)| *id).max().unwrap_or(0);
    if recorded_head > head
        || recorded
            .iter()
            .any(|(id, _)| !supported.iter().any(|(s, _)| s == id))
    {
        return Err(OpenError::Newer {
            path: path.to_path_buf(),
            recorded: recorded_head,
            supported: head,
        });
    }
    if recorded_head < head {
        return Err(OpenError::Older {
            path: path.to_path_buf(),
            recorded: recorded_head,
            supported: head,
        });
    }
    let mismatched: Vec<String> = supported
        .iter()
        .filter(|(id, name)| !recorded.iter().any(|(r, n)| r == id && n == name))
        .map(|(id, name)| {
            let found = recorded
                .iter()
                .find(|(r, _)| r == id)
                .map(|(_, n)| n.as_str());
            format!("{id}_{name} (recorded: {})", found.unwrap_or("nothing"))
        })
        .collect();
    if mismatched.is_empty() {
        Ok(())
    } else {
        Err(OpenError::Divergent {
            path: path.to_path_buf(),
            detail: mismatched.join(", "),
        })
    }
}

fn sqlite_error(path: &Path) -> impl Fn(rusqlite::Error) -> OpenError + '_ {
    move |error| OpenError::Sqlite {
        path: path.to_path_buf(),
        source: error.to_string(),
    }
}

/// Reads the ledger without writing anything (no WAL recovery writes either:
/// SQLite reads a WAL database read-only when its -shm file exists).
fn recorded_migrations(path: &Path) -> Result<Vec<(i64, String)>, OpenError> {
    let conn = Connection::open_with_flags(
        path,
        OpenFlags::SQLITE_OPEN_READ_ONLY | OpenFlags::SQLITE_OPEN_NO_MUTEX,
    )
    .map_err(sqlite_error(path))?;
    let has_ledger: bool = conn
        .query_row(
            "SELECT EXISTS(SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'effect_sql_migrations')",
            [],
            |row| row.get(0),
        )
        .map_err(sqlite_error(path))?;
    if !has_ledger {
        return Ok(Vec::new());
    }
    let mut statement = conn
        .prepare("SELECT migration_id, name FROM effect_sql_migrations ORDER BY migration_id")
        .map_err(sqlite_error(path))?;
    let rows = statement
        .query_map([], |row| Ok((row.get(0)?, row.get(1)?)))
        .map_err(sqlite_error(path))?;
    rows.collect::<Result<_, _>>().map_err(sqlite_error(path))
}

/// The connection settings `Sqlite.ts` applies before migrating.
pub(crate) fn configure(conn: &Connection, fresh: bool) -> rusqlite::Result<()> {
    conn.busy_timeout(std::time::Duration::from_millis(5000))?;
    conn.execute_batch("PRAGMA foreign_keys = ON;")?;
    if fresh {
        conn.execute_batch("PRAGMA auto_vacuum = INCREMENTAL;")?;
    }
    let _: String = conn.query_row("PRAGMA journal_mode = WAL", [], |row| row.get(0))?;
    conn.execute_batch(
        "PRAGMA synchronous = NORMAL;
         PRAGMA checkpoint_fullfsync = ON;
         PRAGMA temp_store = MEMORY;",
    )?;
    let _: i64 = conn.query_row(
        &format!("PRAGMA journal_size_limit = {WAL_SIZE_LIMIT_BYTES}"),
        [],
        |row| row.get(0),
    )?;
    Ok(())
}

/// After migrating, `Sqlite.ts` drops collected statistics so queries use
/// indexes by default.
fn reset_statistics(conn: &Connection) -> rusqlite::Result<()> {
    let has_stats: bool = conn.query_row(
        "SELECT EXISTS(SELECT 1 FROM sqlite_schema WHERE name = 'sqlite_stat1')",
        [],
        |row| row.get(0),
    )?;
    if has_stats {
        conn.execute_batch("DELETE FROM sqlite_stat1; ANALYZE sqlite_schema;")?;
    }
    Ok(())
}

/// Creates the database at `path` with the reference's schema. It is built in
/// a scratch directory beside `path` and hard-linked into place, so a crash
/// leaves no partial database and an existing one is never replaced.
fn create(path: &Path) -> Result<(), OpenError> {
    let directory = path.parent().unwrap_or(Path::new("."));
    let io_error = |error: std::io::Error| OpenError::Sqlite {
        path: path.to_path_buf(),
        source: error.to_string(),
    };
    let scratch = tempfile::Builder::new()
        .prefix(&format!(".statev2-create-{}-", std::process::id()))
        .tempdir_in(directory)
        .map_err(io_error)?;
    let staged = scratch.path().join(FILE_NAME);
    {
        let mut conn = Connection::open(&staged).map_err(sqlite_error(path))?;
        configure(&conn, true).map_err(sqlite_error(path))?;
        let transaction = conn.transaction().map_err(sqlite_error(path))?;
        transaction
            .execute_batch(REFERENCE_SCHEMA)
            .map_err(sqlite_error(path))?;
        transaction
            .execute(
                "INSERT INTO orchestration_v2_projection_metadata (projection_name, schema_version, last_sequence, updated_at)
                 VALUES (?1, 1, 0, ?2)",
                rusqlite::params![THREAD_PROJECTIONS, iso_now()],
            )
            .map_err(sqlite_error(path))?;
        transaction.commit().map_err(sqlite_error(path))?;
        reset_statistics(&conn).map_err(sqlite_error(path))?;
        // Fold the WAL into the file, so the link below publishes everything.
        conn.execute_batch("PRAGMA wal_checkpoint(TRUNCATE);")
            .map_err(sqlite_error(path))?;
        conn.close()
            .map_err(|(_, error)| sqlite_error(path)(error))?;
    }
    match std::fs::hard_link(&staged, path) {
        Ok(()) => Ok(()),
        // Another process published one first; use that.
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => Ok(()),
        Err(error) => Err(io_error(error)),
    }
}

fn iso_now() -> String {
    time::OffsetDateTime::now_utc()
        .format(&time::format_description::well_known::Rfc3339)
        .map(|text| {
            // Millisecond precision with a `Z`, as `DateTime.formatIso` writes.
            let (seconds, rest) = text
                .split_once('.')
                .unwrap_or((text.trim_end_matches('Z'), "000Z"));
            let millis: String = rest
                .trim_end_matches('Z')
                .chars()
                .chain("000".chars())
                .take(3)
                .collect();
            format!("{}.{millis}Z", seconds.trim_end_matches('Z'))
        })
        .unwrap_or_default()
}

/// Opens `statev2.sqlite` in `state_dir` for reading and writing, creating it
/// when the home has none. Refuses (without writing) a database at any other
/// migration head.
pub fn open(state_dir: &Path) -> Result<Connection, OpenError> {
    let path = state_dir.join(FILE_NAME);
    if !path.exists() {
        if state_dir.join(V1_FILE_NAME).exists() {
            return Err(OpenError::UnimportedV1 {
                path: state_dir.to_path_buf(),
            });
        }
        create(&path)?;
    }
    check_ledger(&path, &recorded_migrations(&path)?)?;
    let conn = Connection::open(&path).map_err(sqlite_error(&path))?;
    configure(&conn, false).map_err(sqlite_error(&path))?;
    reset_statistics(&conn).map_err(sqlite_error(&path))?;
    Ok(conn)
}

/// What [`load_into`] took from the database.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Loaded {
    pub projects: usize,
    pub threads: usize,
    /// Threads this server's log held that the database changed since, or
    /// deleted.
    pub replaced: usize,
}

fn project_from_row(id: &str, row: &serde_json::Value) -> crate::Project {
    crate::Project {
        id: id.to_owned(),
        name: row["title"].as_str().unwrap_or_default().to_owned(),
        path: row["workspaceRoot"].as_str().unwrap_or_default().to_owned(),
        created_at: time::OffsetDateTime::parse(
            row["createdAt"].as_str().unwrap_or_default(),
            &time::format_description::well_known::Rfc3339,
        )
        .map_or(0, |at| {
            (at.unix_timestamp_nanos() / 1_000_000).max(0) as u64
        }),
    }
}

/// Reconciles the store rebuilt from this server's log with the database
/// (docs/shared-store.md, 2.2). A project or thread the log does not hold,
/// or that the database changed after the log's last commit to it (the
/// reference changed it while it owned the home), is taken from the
/// database; a thread the database deleted is deleted. Everything else keeps
/// the log's richer state.
pub fn load_into(conn: &Connection, store: &mut crate::Store) -> rusqlite::Result<Loaded> {
    let mut loaded = Loaded::default();
    for row in read::projects(conn)? {
        let Some(id) = row["id"].as_str().map(str::to_owned) else {
            continue;
        };
        if store.project_rows.contains_key(&id) {
            let logged = store.project_sequences.get(&id).copied().unwrap_or(0);
            if read::project_sequence(conn, &id)? <= logged {
                continue;
            }
        }
        if row["deletedAt"].is_null() {
            store
                .projects
                .insert(id.clone(), project_from_row(&id, &row));
            loaded.projects += 1;
        } else {
            store.projects.remove(&id);
        }
        store.stored_project_ids.insert(id.clone());
        store.project_rows.insert(id, row);
    }
    for id in read::deleted_thread_ids(conn)? {
        if store.threads.remove(&id).is_some() {
            loaded.replaced += 1;
        }
        store.deleted_thread_ids.insert(id);
    }
    let mut wanted = Vec::new();
    for id in read::thread_ids(conn)? {
        if let Some(thread) = store.threads.get(&id) {
            let logged = store.thread_sequences.get(&id).copied().unwrap_or(0);
            if thread.stored.is_some() || read::thread_sequence(conn, &id)? <= logged {
                continue;
            }
            loaded.replaced += 1;
        } else if store.deleted_thread_ids.contains(&id) {
            continue;
        } else {
            loaded.threads += 1;
        }
        wanted.push(id);
    }
    if wanted.is_empty() {
        return Ok(loaded);
    }
    // Only each thread's slim records now; its whole projection is read
    // through `reader` when first needed (`stored_projection`).
    let mut slim = read::slim_projections(conn, &wanted.iter().cloned().collect())?;
    let reader: Arc<dyn crate::stored_projection::Hydrate> = Arc::new(Reader::beside(conn)?);
    store.stored_source = Some(reader.clone());
    for id in wanted {
        let Some(slim) = slim.remove(&id) else {
            continue;
        };
        let root = slim.projection["thread"]["projectId"]
            .as_str()
            .and_then(|project| store.projects.get(project))
            .map(|project| project.path.clone());
        let thread = crate::Thread::from_slim(slim, root.as_deref(), reader.clone());
        store.threads.insert(id, thread);
    }
    Ok(loaded)
}

/// Connections of its own to the database, that read a thread's whole
/// projection when it is first needed (`stored_projection::Hydrate`). The
/// database is in WAL mode, so they read beside the writer's connection.
/// Several, so opening one long thread does not hold up reading another.
pub(crate) struct Reader {
    path: std::path::PathBuf,
    idle: std::sync::Mutex<Vec<Connection>>,
}

/// How many reader connections a server keeps open at most.
const READERS: usize = 4;

impl Reader {
    /// A reader of the database `conn` has open.
    pub(crate) fn beside(conn: &Connection) -> rusqlite::Result<Self> {
        let path = conn
            .path()
            .filter(|path| !path.is_empty())
            .ok_or_else(|| rusqlite::Error::InvalidPath(std::path::PathBuf::from(":memory:")))?;
        let reader = Connection::open(path)?;
        configure(&reader, false)?;
        Ok(Self {
            path: std::path::PathBuf::from(path),
            idle: std::sync::Mutex::new(vec![reader]),
        })
    }

    /// Runs `read` in one read transaction (the thread's rows as of one
    /// commit) on an idle connection, or a new one.
    fn with_connection<T>(
        &self,
        read: impl FnOnce(&Connection) -> anyhow::Result<T>,
    ) -> anyhow::Result<T> {
        let idle = self.idle.lock().unwrap_or_else(|e| e.into_inner()).pop();
        let conn = match idle {
            Some(conn) => conn,
            None => {
                let conn = Connection::open(&self.path)?;
                configure(&conn, false)?;
                conn
            }
        };
        conn.execute_batch("BEGIN")?;
        let result = read(&conn);
        let _ = conn.execute_batch("COMMIT");
        let mut idle = self.idle.lock().unwrap_or_else(|e| e.into_inner());
        if idle.len() < READERS {
            idle.push(conn);
        }
        result
    }
}

impl crate::stored_projection::Hydrate for Reader {
    fn read(&self, thread_id: &str) -> anyhow::Result<Option<serde_json::Value>> {
        self.with_connection(|conn| Ok(read::thread_projection(conn, thread_id)?))
    }

    fn read_both(
        &self,
        thread_id: &str,
    ) -> anyhow::Result<Option<(serde_json::Value, crate::stored_projection::Slim)>> {
        self.with_connection(|conn| {
            let Some(projection) = read::thread_projection(conn, thread_id)? else {
                return Ok(None);
            };
            let ids = std::iter::once(thread_id.to_owned()).collect();
            let slim = read::slim_projections(conn, &ids)?.remove(thread_id);
            Ok(slim.map(|slim| (projection, slim)))
        })
    }
}

/// This server's own threads and projects the database has no row for:
/// what the one-time import of `events.jsonl` writes there (2.3). Deleted
/// threads are not imported; a deleted project is, as the reference keeps
/// it, marked deleted.
pub fn missing_from_database(
    conn: &Connection,
    store: &crate::Store,
) -> rusqlite::Result<(Vec<String>, Vec<String>)> {
    let known_threads: std::collections::HashSet<String> = read::thread_ids(conn)?
        .into_iter()
        .chain(read::deleted_thread_ids(conn)?)
        .collect();
    let mut threads: Vec<String> = store
        .threads
        .iter()
        .filter(|(id, thread)| thread.stored.is_none() && !known_threads.contains(*id))
        .map(|(id, _)| id.clone())
        .collect();
    threads.sort();
    let known_projects: std::collections::HashSet<String> = read::projects(conn)?
        .into_iter()
        .filter_map(|row| row["id"].as_str().map(str::to_owned))
        .collect();
    let projects = store
        .project_rows
        .keys()
        .filter(|id| !known_projects.contains(*id))
        .cloned()
        .collect();
    Ok((threads, projects))
}

